"""Turn benchmark summaries into config/capabilities.yaml and load it for routing."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

from governed_agent_engine.core import validate as v
from governed_agent_engine.core.errors import ConfigError

# Which measured dimensions matter for which task type (weights sum to 1).
TASK_TYPE_WEIGHTS: dict[str, dict[str, float]] = {
    "repo_maintain": {"coding": 0.6, "structured": 0.2, "instruction": 0.2},
    "research": {"honesty": 0.4, "reasoning": 0.3, "long_context": 0.3},
    "market_watch": {"reasoning": 0.5, "honesty": 0.3, "structured": 0.2},
    "email_triage": {"instruction": 0.5, "structured": 0.3, "honesty": 0.2},
    "governance_check": {"structured": 0.5, "reasoning": 0.3, "honesty": 0.2},
    "custom": {"structured": 0.3, "instruction": 0.25, "reasoning": 0.25, "honesty": 0.2},
}
PRIOR = 0.5  # Bayesian shrinkage toward 0.5 so 2/2 doesn't beat 9/10
PRIOR_WEIGHT = 2.0


@dataclass(frozen=True, slots=True)
class DimScore:
    score: float
    n: int

    @property
    def smoothed(self) -> float:
        return (self.score * self.n + PRIOR * PRIOR_WEIGHT) / (self.n + PRIOR_WEIGHT)


@dataclass(frozen=True, slots=True)
class EndpointCapability:
    name: str
    model: str
    dims: dict[str, DimScore]
    error_rate: float
    p50_ms: float
    p95_ms: float

    def utility(self, weights: dict[str, float]) -> float:
        """Weighted smoothed score x reliability. Missing dimensions use the prior."""
        total = sum(
            w * (self.dims[d].smoothed if d in self.dims else PRIOR) for d, w in weights.items()
        )
        return round(total * (1.0 - self.error_rate), 4)


@dataclass(frozen=True, slots=True)
class Capabilities:
    suite_version: str
    generated_at: str
    endpoints: dict[str, EndpointCapability]
    weights: dict[str, dict[str, float]] = field(default_factory=lambda: dict(TASK_TYPE_WEIGHTS))

    def utility(self, endpoint: str, task_type: str) -> float | None:
        cap = self.endpoints.get(endpoint)
        if cap is None:
            return None
        return cap.utility(self.weights.get(task_type, self.weights["custom"]))

    def _dim(self, name: str, dimension: str) -> float:
        dims = self.endpoints[name].dims
        return dims[dimension].smoothed if dimension in dims else PRIOR

    def best_for(self, dimension: str, among: list[str] | None = None) -> list[str]:
        names = [n for n in self.endpoints if among is None or n in among]
        return sorted(
            names,
            key=lambda n: (
                -self._dim(n, dimension),
                self.endpoints[n].error_rate,
                n,
            ),
        )


def build_capabilities(
    summary: dict[str, dict[str, Any]], suite_version: str, source: str
) -> dict[str, Any]:
    eps: dict[str, Any] = {}
    for name, s in sorted(summary.items()):
        eps[name] = {
            "model": s["model_requested"],
            "models_served": s["models_served"],
            "error_rate": s["error_rate"],
            "p50_ms": s["p50_ms"],
            "p95_ms": s["p95_ms"],
            "scores": {d: {"score": x["score"], "n": x["n"]} for d, x in s["dimensions"].items()},
        }
    return {
        "suite_version": suite_version,
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "source": source,
        "note": "GENERATED by `gae bench --write-capabilities`. Small samples; see "
        "the benchmark docs for caveats.",
        "task_type_weights": TASK_TYPE_WEIGHTS,
        "endpoints": eps,
    }


def write_capabilities(data: dict[str, Any], path: Path) -> None:
    path.write_text(
        "# " + data["note"] + "\n" + yaml.safe_dump(data, sort_keys=True), encoding="utf-8"
    )


def load_capabilities(path: Path) -> Capabilities | None:
    if not path.is_file():
        return None
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    d = v.as_mapping(raw, "capabilities")
    try:
        eps_raw = v.as_mapping(d.get("endpoints", {}), "capabilities.endpoints")
        eps: dict[str, EndpointCapability] = {}
        for name, e in eps_raw.items():
            em = v.as_mapping(e, f"capabilities.{name}")
            scores = v.as_mapping(em.get("scores", {}), f"capabilities.{name}.scores")
            eps[name] = EndpointCapability(
                name=name,
                model=str(em.get("model", "")),
                dims={
                    dim: DimScore(
                        v.f(v.as_mapping(x, dim).get("score"), f"{name}.{dim}", ge=0, le=1),
                        v.i(v.as_mapping(x, dim).get("n"), f"{name}.{dim}.n", ge=0),
                    )
                    for dim, x in scores.items()
                },
                error_rate=v.f(em.get("error_rate", 0.0), f"{name}.error_rate", ge=0, le=1),
                p50_ms=v.f(em.get("p50_ms", 0.0), f"{name}.p50_ms", ge=0),
                p95_ms=v.f(em.get("p95_ms", 0.0), f"{name}.p95_ms", ge=0),
            )
        weights_raw = v.as_mapping(d.get("task_type_weights", TASK_TYPE_WEIGHTS), "weights")
        weights = {
            t: {dim: v.f(w, f"weights.{t}.{dim}", ge=0) for dim, w in v.as_mapping(ws, t).items()}
            for t, ws in weights_raw.items()
        }
    except ValueError as exc:
        raise ConfigError(f"invalid capabilities.yaml: {exc}") from exc
    if "custom" not in weights:
        weights["custom"] = TASK_TYPE_WEIGHTS["custom"]
    return Capabilities(
        suite_version=str(d.get("suite_version", "")),
        generated_at=str(d.get("generated_at", "")),
        endpoints=eps,
        weights=weights,
    )
